def main():
    raw = json.loads(DATA.read_text(encoding="utf-8"))
    skills_doc = json.loads(SKILLS.read_text(encoding="utf-8")) if SKILLS.exists() else {"prompts": []}
    skill_prompts = skills_doc.get("prompts") or [p for p in raw["prompts"] if any(str(t).startswith("skill:") for t in (p.get("tags") or []))]
    roles = raw["roles"]
    role_ids = {r["id"] for r in roles}

    # rewrite existing nonskill
    out_prompts = []
    seen = set()
    missing = []
    for p in raw["prompts"]:
        tags = list(p.get("tags") or [])
        is_skill = any(str(t).startswith("skill:") for t in tags)
        if is_skill:
            # keep skill body; strip category_id dependency for flat model
            item = {**p, "category_id": "", "tags": tags}
            out_prompts.append(item)
            seen.add(p["id"])
            continue
        if p["id"] in BODIES:
            name, body, extra = BODIES[p["id"]]
            tags2 = list(dict.fromkeys([t for t in tags if not str(t).startswith("cat:")] + extra + ["ide"]))
            out_prompts.append({
                **{k: p.get(k) for k in ("id", "role_id", "order", "builtin", "system", "favorite", "pinned")},
                "name": name,
                "body": body,
                "category_id": "",
                "tags": tags2,
                "test_values": p.get("test_values") or {},
            })
            seen.add(p["id"])
        else:
            missing.append(p["id"])

    if missing:
        raise SystemExit(f"missing rewrites for: {missing}")

    # add new
    for role, name, body, tags in NEW:
        if role not in role_ids:
            raise SystemExit(f"unknown role {role}")
        nid = new_pid(f"{role}|{name}")
        if nid in seen:
            nid = new_pid(f"{role}|{name}|v2")
        out_prompts.append({
            "id": nid,
            "name": name,
            "body": body,
            "role_id": role,
            "category_id": "",
            "order": 500,
            "builtin": True,
            "system": True,
            "tags": tags,
            "test_values": {},
        })
        seen.add(nid)

    # normalize skill prompts category_id empty
    for p in out_prompts:
        p["category_id"] = ""
        p["builtin"] = True
        p["system"] = True

    # sort: by role order then name
    role_order = {r["id"]: int(r.get("order") or 0) for r in roles}
    out_prompts.sort(key=lambda p: (role_order.get(p["role_id"], 999), (p.get("name") or "").casefold()))

    doc = {
        "format": "promptbuilder-builtins",
        "version": 6,
        "note": "2.10.0 flat Role › Prompt; categories omitted; IDE prompts enriched",
        "roles": roles,
        "categories": [],  # flat IA
        "prompts": out_prompts,
    }
    DATA.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # counts
    from collections import Counter
    c = Counter(p["role_id"] for p in out_prompts)
    print("Wrote", DATA, "prompts", len(out_prompts))
    for r in roles:
        print(f"  {r['name']}: {c.get(r['id'], 0)}")
    # median body
    lens = sorted(len(p["body"]) for p in out_prompts if not any(str(t).startswith("skill:") for t in (p.get("tags") or [])))
    print("nonskill median body len", lens[len(lens)//2] if lens else 0, "min", lens[0] if lens else 0, "max", lens[-1] if lens else 0)

