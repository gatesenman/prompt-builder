ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "builtins.json"
SKILLS = ROOT / "data" / "_skills_only.json"

def pid(*parts: str) -> str:
    h = hashlib.sha1("|".join(parts).encode()).hexdigest()[:10]
    return f"bp-{h}"

def new_pid(key: str) -> str:
    return "bp-n" + hashlib.sha1(key.encode()).hexdigest()[:9]

# ---------- template helpers ----------
def T(role_line: str, sections: list[str]) -> str:
    parts = [role_line.strip(), ""]
    for s in sections:
        parts.append(s.rstrip())
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"

# Rich rewritten bodies keyed by existing prompt id
BODIES: dict[str, tuple[str, str, list[str]]] = {}  # id -> (name, body, tags)

def add(pid_: str, name: str, body: str, tags: list[str] | None = None):
    BODIES[pid_] = (name, body.strip() + "\n", tags or [])

